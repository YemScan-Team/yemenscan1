"""
Test Suite for Phase 1 Defect Reproduction and Verification.

Tests cover:
1. NameError on Optional in core.stage1_discovery.run_naabu
2. Fake/default open ports (80/443) injected when no ports were discovered
3. Synthetic HTTP 200 responses injected by run_httpx when connection fails
4. Fake WAP-AUDIT-BASELINE generated by run_wapiti_dast when connection fails
5. Pipeline declaring 100% success (is_completed=True, has_error=False) when tools fail
6. Cancelled/stopped scan status overwritten by late updates
7. Preservation of successful stage results when a subsequent stage fails
"""

import os
import sys
import json
import shutil
import tempfile
import unittest
from unittest.mock import patch, MagicMock

# Add project root to sys.path
BASE_DIR = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
if BASE_DIR not in sys.path:
    sys.path.insert(0, BASE_DIR)

from core.session import create_scan_session, get_status, update_status
import core.stage1_discovery as s1
import core.stage2_web_probing as s2
import core.stage3_vulnerabilities as s3
from core.pipeline import run_full_pipeline


class TestPhase1Defects(unittest.TestCase):

    def setUp(self):
        self.test_dir = tempfile.mkdtemp(prefix="ys_test_")
        self.scan_id = "test_scan_phase1_001"
        self.session_dir = os.path.join(self.test_dir, self.scan_id)
        os.makedirs(self.session_dir, exist_ok=True)

        # Create basic status.json
        status_path = os.path.join(self.session_dir, "status.json")
        with open(status_path, "w", encoding="utf-8") as f:
            json.dump({
                "scan_id": self.scan_id,
                "target_domain": "testtarget.local",
                "current_stage": "queued",
                "progress_percentage": 0,
                "logs": [],
                "is_completed": False,
                "has_error": False,
                "error_message": None,
                "stats": {
                    "subdomains_count": 0,
                    "open_ports_count": 0,
                    "live_urls_count": 0,
                    "api_endpoints_count": 0,
                    "vulnerabilities_count": 0,
                    "vuln_by_severity": {"critical": 0, "high": 0, "medium": 0, "low": 0, "info": 0}
                }
            }, f)

    def tearDown(self):
        shutil.rmtree(self.test_dir, ignore_errors=True)

    @patch("core.stage1_discovery.update_status")
    @patch("core.stage1_discovery.run_docker_tool")
    @patch("core.stage1_discovery._test_tcp_port")
    @patch("socket.gethostbyname")
    def test_01_naabu_optional_not_defined(self, mock_gethost, mock_tcp, mock_docker, mock_update):
        """
        1. Test that calling run_naabu does not fail with NameError: name 'Optional' is not defined.
        Before fix, defining `_check_port_task` inside run_naabu referencing `Optional[str]`
        raises NameError if Optional is not imported in core.stage1_discovery.
        """
        mock_gethost.return_value = "192.0.2.1"
        mock_docker.return_value = (True, "")
        mock_tcp.return_value = False

        # Execute run_naabu
        try:
            self.assertTrue(hasattr(s1, "Optional"), "Optional is not imported in core.stage1_discovery!")
            ok, ports = s1.run_naabu(["testtarget.local"], self.session_dir, self.scan_id)
            self.assertIsInstance(ok, bool)
            self.assertIsInstance(ports, list)
        except NameError as e:
            self.fail(f"run_naabu raised NameError: {e}")

    @patch("core.stage1_discovery.update_status")
    @patch("core.stage1_discovery.run_docker_tool")
    @patch("core.stage1_discovery._test_tcp_port")
    @patch("socket.gethostbyname")
    def test_02_naabu_no_fake_default_ports(self, mock_gethost, mock_tcp, mock_docker, mock_update):
        """
        3. Test that when zero ports are open (tool finds none and tcp tests return False),
        run_naabu does NOT inject fake default open ports 80 and 443.
        """
        mock_gethost.return_value = "192.0.2.1"
        mock_docker.return_value = (True, "")
        mock_tcp.return_value = False  # No open ports

        ok, ports = s1.run_naabu(["testtarget.local"], self.session_dir, self.scan_id)
        # Ports must be strictly empty because nothing is open!
        self.assertEqual(ports, [], "run_naabu injected fake open ports when none were discovered!")

    @patch("core.stage2_web_probing.get_status")
    @patch("core.stage2_web_probing.update_status")
    @patch("core.stage2_web_probing.run_docker_tool")
    @patch("requests.get")
    def test_03_httpx_no_synthetic_200_on_connection_failure(self, mock_req_get, mock_docker, mock_update, mock_get_status):
        """
        3. Test that run_httpx does NOT create fake {status_code: 200, content_length: 0}
        responses when all connection attempts fail.
        """
        mock_get_status.return_value = {"target_domain": "testtarget.local"}
        mock_docker.return_value = (False, "docker failed")
        # Every HTTP request raises ConnectionError (host down / filtered)
        import requests
        mock_req_get.side_effect = requests.exceptions.ConnectionError("Connection refused")

        ok, web_targets, active_urls = s2.run_httpx(self.session_dir, self.scan_id)

        # Must not fabricate live 200 services
        fake_200s = [wt for wt in web_targets if wt.get("status_code") == 200 and wt.get("content_length") == 0]
        self.assertEqual(len(fake_200s), 0, "run_httpx fabricated synthetic HTTP 200 responses for unreachable hosts!")
        self.assertEqual(active_urls, [], "active_urls should be empty when no server responds!")

    @patch("core.stage3_vulnerabilities.update_status")
    @patch("core.stage3_vulnerabilities.is_scan_cancelled")
    @patch("requests.get")
    def test_04_wapiti_no_fake_baseline_on_connection_failure(self, mock_req_get, mock_cancelled, mock_update):
        """
        3 & 4. Test that run_wapiti_dast does NOT create WAP-AUDIT-BASELINE
        declaring 'No Critical OWASP Misconfigurations' when target connections fail.
        """
        mock_cancelled.return_value = False
        import requests
        mock_req_get.side_effect = requests.exceptions.ConnectionError("Connection refused")

        ok, findings = s3.run_wapiti_dast(self.session_dir, self.scan_id, ["https://testtarget.local"])

        baseline_findings = [f for f in findings if f.get("id") == "WAP-AUDIT-BASELINE"]
        self.assertEqual(len(baseline_findings), 0, "run_wapiti_dast issued fake WAP-AUDIT-BASELINE despite connection failure!")
        self.assertFalse(ok, "run_wapiti_dast should return ok=False when target connections fail!")

    @patch("core.pipeline.get_session_dir")
    @patch("core.pipeline.run_subfinder")
    @patch("core.pipeline.run_naabu")
    @patch("core.pipeline.run_httpx")
    @patch("core.pipeline.run_kiterunner_or_api_probing")
    @patch("core.pipeline.prepare_nuclei_targets")
    @patch("core.pipeline.run_nuclei")
    @patch("core.pipeline.run_wapiti_dast")
    @patch("core.session.get_session_dir")
    def test_05_pipeline_failure_when_all_tools_fail(
        self, mock_sess_dir, mock_wap, mock_nuc, mock_prep, mock_kite, mock_http, mock_naabu, mock_sub, mock_pipe_sess
    ):
        """
        2 & 4. Test that when all scanning tools return failure (False, []),
        the pipeline does NOT declare 100% success with is_completed=True and has_error=False.
        """
        mock_pipe_sess.return_value = self.session_dir
        mock_sess_dir.return_value = self.session_dir

        mock_sub.return_value = (False, [])
        mock_naabu.return_value = (False, [])
        mock_http.return_value = (False, [], [])
        mock_kite.return_value = (False, [])
        mock_prep.return_value = []
        mock_nuc.return_value = (False, [])
        mock_wap.return_value = (False, [])

        run_full_pipeline("testtarget.local", self.scan_id)

        status_path = os.path.join(self.session_dir, "status.json")
        with open(status_path, "r", encoding="utf-8") as f:
            final_status = json.load(f)

        # A run where all tools failed must NOT claim to be successfully completed with no errors!
        self.assertTrue(
            final_status.get("has_error") or final_status.get("status") in ("failed", "partial") or final_status.get("current_stage") in ("failed", "partial"),
            f"Pipeline falsely reported success when all tools failed! Status: {final_status}"
        )
        self.assertNotEqual(
            final_status.get("current_stage"), "phase1_discovery",
            "Pipeline left current_stage stuck at phase1_discovery after pipeline end!"
        )

    @patch("core.session.get_session_dir")
    def test_06_cancelled_scan_not_overwritten(self, mock_sess_dir):
        """
        5. Test that once a scan is marked 'stopped' (cancelled by user),
        late calls to update_status do NOT overwrite it to 'completed' or reset stage.
        """
        mock_sess_dir.return_value = self.session_dir

        # Simulate user cancelling the scan
        update_status(self.scan_id, stage="stopped", is_completed=True, log_message="Scan cancelled by user")
        status_after_stop = get_status(self.scan_id)
        self.assertEqual(status_after_stop.get("current_stage"), "stopped")

        # Simulate a trailing/late callback attempting to report completion
        update_status(self.scan_id, stage="completed", progress=100, is_completed=True, log_message="Late callback")
        status_after_late = get_status(self.scan_id)

        self.assertEqual(
            status_after_late.get("current_stage"), "stopped",
            "Late update_status call overwrote 'stopped' stage with 'completed'!"
        )

    @patch("core.pipeline.get_session_dir")
    @patch("core.pipeline.run_subfinder")
    @patch("core.pipeline.run_naabu")
    @patch("core.pipeline.run_httpx")
    @patch("core.pipeline.run_kiterunner_or_api_probing")
    @patch("core.pipeline.prepare_nuclei_targets")
    @patch("core.pipeline.run_nuclei")
    @patch("core.pipeline.run_wapiti_dast")
    @patch("core.session.get_session_dir")
    def test_07_preserve_successful_stages_on_later_stage_failure(
        self, mock_sess_dir, mock_wap, mock_nuc, mock_prep, mock_kite, mock_http, mock_naabu, mock_sub, mock_pipe_sess
    ):
        """
        5. Test that when an early stage succeeds (Subfinder, Naabu, HTTPX)
        and a later stage fails (Nuclei, Wapiti), the pipeline preserves
        prior results and sets the status to 'partial' (not wiping data, not claiming 100% completed success).
        """
        mock_pipe_sess.return_value = self.session_dir
        mock_sess_dir.return_value = self.session_dir

        # Early stages succeed
        mock_sub.return_value = (True, ["testtarget.local", "api.testtarget.local"])
        mock_naabu.return_value = (True, ["testtarget.local:443", "api.testtarget.local:443"])
        mock_http.return_value = (True, [{"url": "https://testtarget.local", "status_code": 200}], ["https://testtarget.local"])
        mock_kite.return_value = (True, [{"url": "https://testtarget.local/api/v1/health", "status_code": 200}])
        mock_prep.return_value = ["https://testtarget.local"]

        # Later vulnerability stage fails
        mock_nuc.return_value = (False, [])
        mock_wap.return_value = (False, [])

        run_full_pipeline("testtarget.local", self.scan_id)

        status_path = os.path.join(self.session_dir, "status.json")
        with open(status_path, "r", encoding="utf-8") as f:
            final_status = json.load(f)

        # Must report partial due to tool failures despite earlier success
        self.assertEqual(final_status.get("status"), "partial", f"Expected status 'partial', got: {final_status.get('status')}")
        self.assertTrue(final_status.get("has_error"), "Expected has_error=True when tools in pipeline fail!")

        # Tool statuses must distinguish success from failure
        tool_statuses = final_status.get("tool_statuses", {})
        self.assertEqual(tool_statuses.get("subfinder"), "success")
        self.assertEqual(tool_statuses.get("naabu"), "success")
        self.assertEqual(tool_statuses.get("httpx"), "success")
        self.assertEqual(tool_statuses.get("nuclei"), "failed")
        self.assertEqual(tool_statuses.get("wapiti"), "failed")


if __name__ == "__main__":
    unittest.main()
